CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    banned BOOLEAN NOT NULL DEFAULT FALSE,
    birth_date DATE NOT NULL,
    closed_access BOOLEAN NOT NULL DEFAULT FALSE,
    consent BOOLEAN NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    email VARCHAR(255) NOT NULL,
    first_name VARCHAR(255) NOT NULL,
    last_name VARCHAR(255) NOT NULL,
    parent_consent BOOLEAN NOT NULL,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(40) NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE contests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description TEXT NOT NULL,
    end_age INTEGER NOT NULL,
    name VARCHAR(255) NOT NULL,
    start_age INTEGER NOT NULL,
    CONSTRAINT uk_contests_name UNIQUE (name)
);

CREATE TABLE applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    description TEXT NOT NULL,
    is_curator BOOLEAN NOT NULL DEFAULT FALSE,
    is_team BOOLEAN NOT NULL DEFAULT FALSE,
    mentor VARCHAR(255),
    name VARCHAR(255) NOT NULL,
    organization TEXT,
    contest_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    CONSTRAINT fk_applications_contest FOREIGN KEY (contest_id) REFERENCES contests(id),
    CONSTRAINT fk_applications_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE works (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    broken BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    file_name VARCHAR(255) NOT NULL,
    file_size INTEGER NOT NULL,
    is_rated BOOLEAN NOT NULL DEFAULT FALSE,
    name VARCHAR(255) NOT NULL,
    rate INTEGER,
    application_id BIGINT NOT NULL,
    CONSTRAINT fk_works_application FOREIGN KEY (application_id) REFERENCES applications(id),
    CONSTRAINT uk_works_name_application UNIQUE (name, application_id)
);

CREATE TABLE members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    birth_date DATE NOT NULL,
    first_name VARCHAR(255) NOT NULL,
    last_name VARCHAR(255) NOT NULL,
    application_id BIGINT NOT NULL,
    CONSTRAINT fk_members_application FOREIGN KEY (application_id) REFERENCES applications(id)
);

CREATE INDEX idx_users_role ON users(role);
CREATE INDEX idx_users_banned ON users(banned);
CREATE INDEX idx_applications_user_id ON applications(user_id);
CREATE INDEX idx_applications_contest_id ON applications(contest_id);
CREATE INDEX idx_works_application_id ON works(application_id);
CREATE INDEX idx_members_application_id ON members(application_id);
